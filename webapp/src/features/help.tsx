/** Кнопка «?» для верхней панели. */
export function HelpButton() {
  const open = useStore((s) => s.helpOpen);
  const set = useStore((s) => s.openHelp);
  return (
    <button className="help-btn" type="button" aria-label="Справка" aria-haspopup="dialog" aria-expanded={open} title="Справка" onClick={() => set(true)}>
      ?
    </button>
  );
}

/** Окно справки: справа на десктопе, снизу на телефоне; закрывается Esc, крестиком и кликом мимо. */
export function HelpSheet() {
  const open = useStore((s) => s.helpOpen);
  const set = useStore((s) => s.openHelp);
  const close = useRef<HTMLButtonElement>(null);
  useEffect(() => {
    if (!open) return;
    const back = document.activeElement as HTMLElement | null;
    close.current?.focus();
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && set(false);
    window.addEventListener("keydown", onKey);
    return () => {
      window.removeEventListener("keydown", onKey);
      back?.focus?.();
    };
  }, [open, set]);
  if (!open) return null;
  return (
    <div className="help-back" onClick={() => set(false)}>
      <aside className="help-sheet" role="dialog" aria-modal="true" aria-label="Справка" onClick={(e) => e.stopPropagation()}>
        <div className="help-h">
          <h2>Справка</h2>
          <button ref={close} className="btn" type="button" aria-label="Закрыть справку" onClick={() => set(false)}>
            ✕
          </button>
        </div>
        <div className="help">
          {HELP.map(([title, paras]) => (
            <details key={title}>
              <summary>{title}</summary>
              <div className="hb">
                {paras.map((p) => (
                  <p key={p}>{p}</p>
                ))}
              </div>
            </details>
          ))}
        </div>
      </aside>
    </div>
  );
}
